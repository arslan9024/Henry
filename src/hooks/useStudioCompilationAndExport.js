/**
 * [Category 2: Business Logic / Hook]
 * White Caves Real Estate - Studio Compilation & Export Hook
 * Encapsulates PDF package compilation, vault auto-save, download & WhatsApp dispatch (< 85 lines).
 */

import { useDispatch, useSelector } from 'react-redux';
import { setCompilingState, setCompiledPackageResult } from '../store/tenancyStudioSlice';
import { setActivePreviewDoc } from '../store/documentVaultSlice';
import { compileTenancyPackage } from '../services/tenancyStudio/multiDocPackageCompiler';
import { saveDocumentToVault } from '../services/vault/documentVaultService';

export const useStudioCompilationAndExport = ({ combineContract, combineAddendum, combineReceipt }) => {
  const dispatch = useDispatch();
  const page1 = useSelector((state) => state.tenancyStudio?.page1 || {});
  const page3 = useSelector((state) => state.tenancyStudio?.page3 || {});
  const coordinates = useSelector((state) => state.tenancyStudio?.coordinates);
  const addendumParams = useSelector((state) => state.tenancyStudio?.addendumParams);
  const receiptParams = useSelector((state) => state.tenancyStudio?.receiptParams);
  const confirmations = useSelector((state) => state.tenancyStudio?.confirmations || {});

  const handleProcessPdf = async () => {
    dispatch(setCompilingState(true));
    try {
      let scope = 'full-package';
      if (combineContract && !combineAddendum && !combineReceipt) scope = 'contract-only';
      else if (!combineContract && combineAddendum && !combineReceipt) scope = 'addendum-only';
      else if (!combineContract && !combineAddendum && combineReceipt) scope = 'receipt-only';

      const blob = await compileTenancyPackage({
        scope,
        page1Payload: page1,
        page3Payload: page3,
        coordinates,
        addendumParams,
        receiptParams,
      });

      const blobUrl = URL.createObjectURL(blob);
      const fileName =
        `White_Caves_Tenancy_${page1.property_no || 'Unit'}_${new Date().getFullYear()}.pdf`.replace(
          /\s+/g,
          '_',
        );
      dispatch(setCompiledPackageResult({ blobUrl, fileName }));

      await saveDocumentToVault({
        title: `Tenancy Package: Unit ${page1.property_no || ''} ${page1.building_name || ''}`,
        documentType: 'tenancy-contract',
        tenantName: page1.tenant_name,
        propertyNo: page1.property_no,
        buildingName: page1.building_name,
        annualRent: page1.annual_rent,
        blobUrl,
        metadata: { fileName, scope },
      });
    } catch (err) {
      console.error('Compilation failed:', err);
      alert(`Package compilation error: ${err.message}`);
      dispatch(setCompilingState(false));
    }
  };

  const handleDownload = () => {
    if (!confirmations.lastCompiledBlobUrl) {
      handleProcessPdf();
      return;
    }
    const a = document.createElement('a');
    a.href = confirmations.lastCompiledBlobUrl;
    a.download = confirmations.lastFileName || 'White_Caves_Tenancy_Package.pdf';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
  };

  const handleShareWhatsApp = () => {
    const text = encodeURIComponent(
      `Hello ${page1.tenant_name || 'Client'}, here is the summary of your tenancy package for ${page1.property_no || ''} ${page1.building_name || ''}. Annual Rent: ${page1.annual_rent || ''}. Generated by White Caves Real Estate LLC.`,
    );
    window.open(`https://wa.me/?text=${text}`, '_blank');
  };

  const handleOpenPreviewModal = () => {
    if (confirmations.lastCompiledBlobUrl) {
      dispatch(
        setActivePreviewDoc({
          title: `Tenancy Package: ${page1.property_no || 'Unit'} ${page1.building_name || ''}`,
          tenantName: page1.tenant_name,
          propertyNo: page1.property_no,
          blobUrl: confirmations.lastCompiledBlobUrl,
          fileName: confirmations.lastFileName,
          documentType: 'tenancy-contract',
        }),
      );
    } else {
      handleProcessPdf();
    }
  };

  return {
    isCompiling: Boolean(confirmations.isCompiling),
    handleProcessPdf,
    handleDownload,
    handleShareWhatsApp,
    handleOpenPreviewModal,
  };
};

export default useStudioCompilationAndExport;
